import React, { useContext, useMemo, useRef, useState, useEffect } from 'react'
import { MdChatBubbleOutline, MdClose, MdSend } from 'react-icons/md'
import { AuthContext } from '../context/AuthContext.jsx'
import { DataContext } from '../context/DataContext.jsx'

// --------------------------------------------------------------------
// Rule-based dashboard assistant. This is NOT an AI/LLM — every reply is
// produced by simple keyword matching against a fixed set of intents
// below, using data already loaded into DataContext (appointments,
// payments, project stage). No external model or API call is involved.
// --------------------------------------------------------------------

const QUICK_REPLIES = [
  { key: 'login', label: 'Login help' },
  { key: 'book', label: 'Book an appointment' },
  { key: 'appt-status', label: 'My appointment status' },
  { key: 'payment', label: 'Payment help' },
  { key: 'role', label: 'What can I do here?' }
]

function matchIntent(text) {
  const s = text.toLowerCase()
  if (/login|log in|sign in|password|forgot|locked out/.test(s)) return 'login'
  if (/book|schedule|new appointment|slot/.test(s)) return 'book'
  if (/appointment status|my appointment|confirmed|pending appointment|reschedul|cancel.*appointment/.test(s)) return 'appt-status'
  if (/payment|invoice|pay now|transaction|refund|paid|due/.test(s)) return 'payment'
  if (/what can i do|help|role|permission|access/.test(s)) return 'role'
  if (/hi|hello|hey/.test(s)) return 'greeting'
  return 'fallback'
}

function formatDate(iso) {
  if (!iso) return '—'
  return new Date(iso).toLocaleDateString(undefined, { day: '2-digit', month: 'short' })
}

export default function Chatbot() {
  const { user } = useContext(AuthContext)
  const { appointments, payments, projects } = useContext(DataContext)
  const [isOpen, setIsOpen] = useState(false)
  const [input, setInput] = useState('')
  const [messages, setMessages] = useState([])
  const listRef = useRef(null)

  const roleLabel = user?.roleLabel || 'there'

  // Seed the welcome message once, per login, tailored to the role.
  useEffect(() => {
    if (!user) return
    setMessages([
      {
        from: 'bot',
        text: `Hi ${user.name.split(' ')[0]}! I'm the IDCP Assistant. I can help with login issues, booking or checking appointments, and payments. What do you need?`
      }
    ])
  }, [user?.id]) // eslint-disable-line react-hooks/exhaustive-deps

  useEffect(() => {
    listRef.current?.scrollTo({ top: listRef.current.scrollHeight, behavior: 'smooth' })
  }, [messages, isOpen])

  // Every possible reply is assembled from data already in context —
  // nothing here is generated by a model.
  const respond = useMemo(
    () => (intent) => {
      switch (intent) {
        case 'greeting':
          return `Hello! Ask me about login, appointments, or payments — or use the quick options below.`

        case 'login':
          if (user?.role === 'admin') {
            return `You're signed in as Administrator. If a teammate is locked out, an admin can't reset another user's password from this UI yet — for now, check their email/password are typed correctly, or contact IT.`
          }
          return `You're signed in as ${roleLabel}. If you ever get logged out, use your registered email + password on the Login page. Sessions expire after a few hours for security — just log in again.`

        case 'book': {
          if (user?.role === 'customer') {
            const myProject = projects[0]
            return myProject
              ? `To book: go to Appointments → "${'Schedule Appointment'}", pick "${myProject.name}", choose a designer, then a date. Only real open time slots (checked live against the designer's calendar) will be selectable — booked or past slots are disabled automatically.`
              : `To book an appointment, open the Appointments page and use "Schedule Appointment". You'll need a project first — once one is set up for you, it'll appear in the booking form.`
          }
          if (user?.role === 'designer' || user?.role === 'admin') {
            return `Anyone can schedule from the Appointments page — pick a project, a designer, and a date; available slots are pulled live so double-bookings aren't possible. As a ${roleLabel}, you can then Confirm, Reject, or mark appointments Completed from the same page.`
          }
          return `Open the Appointments page and use "Schedule Appointment" to pick a project, designer, date and an open time slot.`
        }

        case 'appt-status': {
          if (!appointments || appointments.length === 0) {
            return `You don't have any appointments yet. Head to the Appointments page to schedule one.`
          }
          const upcoming = [...appointments]
            .filter((a) => !['Cancelled', 'Rejected', 'Completed'].includes(a.status))
            .sort((a, b) => new Date(a.date) - new Date(b.date))
            .slice(0, 3)
          if (upcoming.length === 0) {
            return `You have ${appointments.length} appointment(s) on record, but none are currently upcoming (they're completed, cancelled, or rejected). Check the Appointments page for full history.`
          }
          const lines = upcoming
            .map((a) => `• ${formatDate(a.date)} ${a.time} with ${a.designer} — ${a.status}`)
            .join('\n')
          return `Here's what's coming up:\n${lines}\n\nSee the Appointments page for the full list and to manage them.`
        }

        case 'payment': {
          if (user?.role === 'designer' || user?.role === 'contractor') {
            return `Payments aren't part of the ${roleLabel} view in this portal — that's handled between customers and administrators. Let me know if you need anything about appointments or projects instead.`
          }
          if (!payments || payments.length === 0) {
            return `No payment records found yet.`
          }
          const pending = payments.filter((p) => p.status === 'Pending' || p.status === 'Overdue')
          const paid = payments.filter((p) => p.status === 'Paid')
          let reply = `You have ${paid.length} paid and ${pending.length} pending/overdue invoice(s). `
          if (pending.length > 0) {
            const next = pending[0]
            reply += `Next due: ${next.invoiceId} for ₹${Number(next.amount).toLocaleString('en-IN')} (due ${formatDate(next.dueDate)}). Use the "Pay Now" button on the Payments page — it opens a secure test-mode checkout, no card details are ever stored.`
          } else {
            reply += `You're all caught up! Visit the Payments page any time to see your full history.`
          }
          return reply
        }

        case 'role': {
          const roleHelp = {
            admin: `As Administrator you can manage customers, designers, contractors, suppliers, materials, all projects, appointments, payments, and reports.`,
            designer: `As a Designer you can view your assigned customers and projects, manage materials, and confirm/reject/reschedule your appointments.`,
            customer: `As a Customer you can track your project's stage, view/approve quotations, book appointments with your designer, and pay invoices.`,
            contractor: `As a Contractor you can view your assigned projects, materials, and appointments related to your work.`
          }
          return roleHelp[user?.role] || `I can help with login, appointments, and payments — what do you need?`
        }

        default:
          return `I'm a simple rule-based assistant, so I can only help with: login issues, booking/checking appointments, and payment questions. Try one of the quick options below, or rephrase your question.`
      }
    },
    [user, appointments, payments, projects, roleLabel]
  )

  const send = (text) => {
    const trimmed = text.trim()
    if (!trimmed) return
    const intent = matchIntent(trimmed)
    setMessages((prev) => [...prev, { from: 'user', text: trimmed }, { from: 'bot', text: respond(intent) }])
    setInput('')
  }

  const handleQuickReply = (key) => {
    const label = QUICK_REPLIES.find((q) => q.key === key)?.label || key
    setMessages((prev) => [...prev, { from: 'user', text: label }, { from: 'bot', text: respond(key) }])
  }

  if (!user) return null

  return (
    <div className="chatbot-root">
      {isOpen && (
        <div className="chatbot-panel">
          <div className="chatbot-header">
            <span>IDCP Assistant</span>
            <button className="chatbot-icon-btn" onClick={() => setIsOpen(false)} aria-label="Close chat">
              <MdClose />
            </button>
          </div>

          <div className="chatbot-messages" ref={listRef}>
            {messages.map((m, i) => (
              <div key={i} className={`chatbot-bubble ${m.from}`}>
                {m.text.split('\n').map((line, li) => (
                  <div key={li}>{line}</div>
                ))}
              </div>
            ))}
          </div>

          <div className="chatbot-quick-replies">
            {QUICK_REPLIES.map((q) => (
              <button key={q.key} className="chatbot-chip" onClick={() => handleQuickReply(q.key)}>
                {q.label}
              </button>
            ))}
          </div>

          <form
            className="chatbot-input-row"
            onSubmit={(e) => {
              e.preventDefault()
              send(input)
            }}
          >
            <input
              type="text"
              value={input}
              onChange={(e) => setInput(e.target.value)}
              placeholder="Type a question…"
            />
            <button type="submit" aria-label="Send" className="chatbot-icon-btn">
              <MdSend />
            </button>
          </form>
        </div>
      )}

      <button className="chatbot-fab" onClick={() => setIsOpen((v) => !v)} aria-label="Open chat assistant">
        {isOpen ? <MdClose /> : <MdChatBubbleOutline />}
      </button>
    </div>
  )
}
